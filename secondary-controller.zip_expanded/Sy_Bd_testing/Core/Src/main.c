void Spot_size_read()
{
  /**********************************************************************
               ADC for Spot size 100um, 200um, 300um, 400um, 500um
   **********************************************************************/

  if(HAL_ADC_PollForConversion(&hadc1, 1000) == HAL_OK) // Poll ADC1 Perihperal & TimeOut = 1mSec
 {
       AD_RES = HAL_ADC_GetValue(&hadc1); // Read The ADC Conversion Result & Map It To PWM DutyCycle

 }


  if ((AD_RES >= 2200) && (AD_RES < 4000))
  {
	  spot_size=0.1;
  }
  else if ((AD_RES > 1800) && (AD_RES <= 2200))
  {
	  spot_size = 0.2;
  }
  else if ((AD_RES > 1410) && (AD_RES <= 1850))
  {
	  spot_size = 0.3;
  }
  else if ((AD_RES > 1110) && (AD_RES <= 1400))
  {
	  spot_size = 0.4;
  }
  else if ((AD_RES <= 1100))//((AD_RES > 100) && (AD_RES <= 800))
  {
	  spot_size = 0.5;
  }

  if(Temp_spot_size == spot_size)
  {
	//HAL_GPIO_WritePin(GPIOC, GPIO_PIN_8, 0);
  }
  else
  {
	  Temp_spot_size = spot_size;
	  //HAL_GPIO_WritePin(GPIOC, GPIO_PIN_8, 1);
  }

 }

